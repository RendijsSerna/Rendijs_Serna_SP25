-- 5. 2 Create a function that adds a new transaction to your transaction table. 
-- You can define the input arguments and output format. 
-- Make sure all transaction attributes can be set with the function (via their natural keys). 
-- The function does not need to return a value but should confirm the successful insertion of the new transaction.
CREATE OR REPLACE FUNCTION Agency.add_transaction(
    in_property_address TEXT,
    in_client_email TEXT,
    in_agent_email TEXT,
    in_transaction_date DATE,
    in_amount DECIMAL
) RETURNS VOID AS $$
DECLARE
    v_property_id BIGINT;
    v_client_id BIGINT;
    v_agent_id BIGINT;
    v_transaction_exists BOOLEAN;
BEGIN

    SELECT p.property_id INTO v_property_id
    FROM Agency.Properties p
    WHERE p.address = in_property_address;


    SELECT c.client_id INTO v_client_id
    FROM Agency.Clients c
    WHERE UPPER(c.email) = UPPER(in_client_email);

    SELECT a.agent_id INTO v_agent_id
    FROM Agency.Agents a
    WHERE UPPER(a.email) = UPPER(in_agent_email);

    SELECT EXISTS (
        SELECT 1 
        FROM Agency.Transactions 
        WHERE property_id = v_property_id 
          AND client_id = v_client_id 
          AND agent_id = v_agent_id 
          AND transaction_date = in_transaction_date
          AND amount = in_amount
    ) INTO v_transaction_exists;

    IF v_transaction_exists THEN
        RAISE NOTICE 'Transaction already exists in the database.';
    ELSE
        -- insert new transaction
        INSERT INTO Agency.Transactions (property_id, client_id, agent_id, transaction_date, amount)
        VALUES (v_property_id, v_client_id, v_agent_id, add_transaction.in_transaction_date, add_transaction.in_amount);

        -- success confirmation
        RAISE NOTICE 'New transaction added successfully.';
    END IF;
END;
$$ LANGUAGE plpgsql;

