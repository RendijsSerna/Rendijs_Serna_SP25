--6. Create a view that presents analytics for the most recently added quarter in your database. Ensure that the result excludes irrelevant fields such as surrogate keys and duplicate entries.
CREATE OR REPLACE VIEW Agency.RecentQuarterAnalytics AS
SELECT
    T.transaction_date,
    P.address,
    P.city,
    P.state,
    P.zip_code,
    P.price,
    A.first_name AS agent_first_name,
    A.last_name AS agent_last_name,
    C.first_name AS client_first_name,
    C.last_name AS client_last_name,
    T.amount
FROM
    Agency.Transactions T
JOIN
    Agency.Properties P ON T.property_id = P.property_id
JOIN
    Agency.Agents A ON T.agent_id = A.agent_id
JOIN
    Agency.Clients C ON T.client_id = C.client_id
WHERE
    T.transaction_date >= CURRENT_DATE - INTERVAL '3 months';

