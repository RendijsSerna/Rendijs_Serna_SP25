CREATE DATABASE realestateagency;


CREATE SCHEMA IF NOT EXISTS Agency;


CREATE TABLE IF NOT EXISTS Agency.PropertyTypes (
    type_id SERIAL PRIMARY KEY,
    type_name VARCHAR(50) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS Agency.Agents (
    agent_id SERIAL PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL,
    phone VARCHAR(15) UNIQUE NOT NULL,
    CONSTRAINT unique_email_phone_agent UNIQUE (email, phone)
);

CREATE TABLE IF NOT EXISTS Agency.Clients (
    client_id SERIAL PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL,
    phone VARCHAR(15) UNIQUE NOT NULL,
    CONSTRAINT unique_email_phone_customer UNIQUE (email, phone)
);

CREATE TABLE IF NOT EXISTS Agency.Properties (
    property_id SERIAL PRIMARY KEY,
    address VARCHAR(255) NOT NULL,
    city VARCHAR(100) NOT NULL,
    state VARCHAR(100) NOT NULL,
    zip_code VARCHAR(10) NOT NULL,
    price DECIMAL(15, 2) NOT NULL CHECK (price > 0),
    agent_id BIGINT NOT NULL,
    CONSTRAINT fk_agent FOREIGN KEY (agent_id) REFERENCES Agency.Agents(agent_id)
);

CREATE TABLE IF NOT EXISTS Agency.PropertyDetails (
    property_id BIGINT NOT NULL,
    type_id BIGINT NOT NULL,
    square_footage INT NOT NULL CHECK (square_footage > 0),
    bedrooms INT NOT NULL CHECK (bedrooms >= 0),
    bathrooms INT NOT NULL CHECK (bathrooms >= 0),
    PRIMARY KEY (property_id, type_id),
    CONSTRAINT fk_property FOREIGN KEY (property_id) REFERENCES Agency.Properties(property_id),
    CONSTRAINT fk_type FOREIGN KEY (type_id) REFERENCES Agency.PropertyTypes(type_id)
);

CREATE TABLE IF NOT EXISTS Agency.Transactions (
    transaction_id SERIAL PRIMARY KEY,
    property_id BIGINT NOT NULL,
    client_id BIGINT NOT NULL,
    agent_id BIGINT NOT NULL,
    transaction_date DATE NOT NULL CHECK (transaction_date >= '2024-01-01') DEFAULT CURRENT_DATE,
    amount DECIMAL(15, 2) NOT NULL CHECK (amount > 0),
    CONSTRAINT fk_property FOREIGN KEY (property_id) REFERENCES Agency.Properties(property_id),
    CONSTRAINT fk_client FOREIGN KEY (client_id) REFERENCES Agency.Clients(client_id),
    CONSTRAINT fk_agent FOREIGN KEY (agent_id) REFERENCES Agency.Agents(agent_id)
);


