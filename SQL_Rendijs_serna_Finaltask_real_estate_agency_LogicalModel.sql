--5.1 Create a function that updates data in one of your tables. This function should take the following input arguments:
--The primary key value of the row you want to update
--The name of the column you want to update
--The new value you want to set for the specified column
--This function should be designed to modify the specified row in the table, updating the specified column with the new value.

CREATE OR REPLACE FUNCTION Agency.update_agent(
    in_agent_id INTEGER,
    in_column_name VARCHAR,
    in_new_value VARCHAR
)
RETURNS VOID AS
$$
BEGIN
    -- Validate that the agent exists
    IF NOT EXISTS (SELECT 1 FROM Agency.Agents WHERE agent_id = in_agent_id) THEN
        RAISE EXCEPTION 'Agent with ID % does not exist', in_agent_id;
    END IF;
    
    -- changes input data to upper (doesent only on phone number)
    IF UPPER(in_column_name) != 'PHONE' THEN
        in_new_value := UPPER(in_new_value);
    END IF;
    
	-- checks 
    IF UPPER(in_column_name) = 'FIRST_NAME' THEN
        UPDATE Agency.Agents 
        SET first_name = in_new_value 
        WHERE agent_id = in_agent_id;
    ELSIF UPPER(in_column_name) = 'LAST_NAME' THEN
        UPDATE Agency.Agents 
        SET last_name = in_new_value 
        WHERE agent_id = in_agent_id;
    ELSIF UPPER(in_column_name) = 'EMAIL' THEN
        UPDATE Agency.Agents 
        SET email = in_new_value 
        WHERE agent_id = in_agent_id;
    ELSIF UPPER(in_column_name) = 'PHONE' THEN
        UPDATE Agency.Agents 
        SET phone = in_new_value  -- Phone remains unchanged case
        WHERE agent_id = in_agent_id;
    ELSE
        RAISE EXCEPTION 'Column "%" does not exist or is not updatable in Agents table', in_column_name;
    END IF;
    
    -- Check if any rows were actually updated
    IF NOT FOUND THEN
        RAISE EXCEPTION 'No rows updated. Value may be the same as existing value';
    END IF;
END;
$$
LANGUAGE plpgsql;

